    def __init__(self, width=128, height=64, scale=2.5):
        self.width = width
        self.height = height
        self.scale = scale

        self.root = tk.Tk()
        self.root.title(f"{width}x{height} LED Matrix")

        self.canvas = tk.Canvas(
            self.root,
            width=width * scale,
            height=height * scale,
            bg="black"
        )
        self.canvas.pack()
    def rgb_to_hex(self,rgb):
        return "#%02x%02x%02x" % rgb  # Convert (R, G, B) to Hex

    def set_pixel(self, x, y, color):
        if 0 <= x < self.width and 0 <= y < self.height:
            s = self.scale

            self.canvas.create_rectangle(
                x * s,
                y * s,
                (x + 1) * s,
                (y + 1) * s,
                fill=color,
                outline="gray"
            )

    def draw_text(self, text, x=0, y=0, color=(255, 255, 255)):
        if isinstance(color, tuple):
            color = "#%02x%02x%02x" % color

        for character_index, character in enumerate(str(text).upper()):
            glyph = self._FONT.get(character, self._FONT["?"])
            origin_x = x + character_index * 6

            for row, line in enumerate(glyph):
                for column, pixel in enumerate(line):
                    if pixel == "1":
                        pixel_x = origin_x + column
                        pixel_y = y + row
                        if 0 <= pixel_x < self.width and 0 <= pixel_y < self.height:
                            left = pixel_x * self.scale
                            top = pixel_y * self.scale
                            self.canvas.create_rectangle(
                                left,
                                top,
                                left + self.scale - 1,
                                top + self.scale - 1,
                                fill=color,
                                outline=""
                            )
    def drawImage(self, image_name="Delta", x1=0, y1=0, color=(0, 0, 0)):
        image_path = self.ImageDictionary.get(image_name, self.ImageDictionary["Delta"])
        img = Image.open(image_path).convert("RGB")

        width, height = img.size
        for y in range(height):
            for x in range(width):
                r, g, b = img.getpixel((x, y))
                self.set_pixel(x + x1, y + y1, self.rgb_to_hex((r, g, b)))

    def clear(self):
        self.canvas.delete("all")

    def show(self):
        self.root.update()

    def run(self):
        self.root.mainloop()